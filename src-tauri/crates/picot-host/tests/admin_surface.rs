#[tokio::test(flavor = "multi_thread")]
async fn forwarded_rows_carry_their_arguments_on_the_wire() {
    let fixture = Fixture::boot().await;
    let mut app = fixture.attach_app().await;
    let surface = Arc::clone(&fixture.surface);

    // Blocking reply helper: call the surface, read the frame, answer, await.
    async fn round_trip(
        app: &mut Client,
        call: impl std::future::Future<Output = Result<Value, String>> + Send + 'static,
    ) -> (Value, Result<Value, String>) {
        let handle = tokio::spawn(call);
        let frame = next_json(app).await;
        let id = frame["id"].as_str().unwrap().to_string();
        send_json(
            app,
            json!({"type": "surface_response", "id": id, "ok": true, "result": {}}),
        )
        .await;
        let result = tokio::time::timeout(Duration::from_secs(10), handle)
            .await
            .expect("settles")
            .expect("no panic");
        (frame, result)
    }

    // open_devtools
    let call = {
        let surface = Arc::clone(&surface);
        async move {
            surface.open_devtools("native-workspace-w1").await?;
            Ok(Value::Null)
        }
    };
    let (frame, outcome) = round_trip(&mut app, call).await;
    assert_eq!(frame["op"], "open_devtools");
    assert_eq!(frame["args"], json!({"label": "native-workspace-w1"}));
    outcome.expect("the op completes");

    // close_window keeps the request id: the app-side settlement needs it (row A10).
    let call = {
        let surface = Arc::clone(&surface);
        async move {
            surface
                .close_window("native-workspace-w1", "close-7")
                .await?;
            Ok(Value::Null)
        }
    };
    let (frame, outcome) = round_trip(&mut app, call).await;
    assert_eq!(frame["op"], "close_window");
    assert_eq!(
        frame["args"],
        json!({"label": "native-workspace-w1", "requestId": "close-7"})
    );
    outcome.expect("the op completes");

    // open_workspace_window carries the committed target, the owner and the capability.
    let call = {
        let surface = Arc::clone(&surface);
        async move {
            surface
                .open_workspace_window(
                    "http://127.0.0.1:51000",
                    &RuntimeTarget {
                        workspace_id: "w1".to_string(),
                        session_id: "s1".to_string(),
                        instance_id: "i1".to_string(),
                        owner_id: Some("o1".to_string()),
                        workspace_generation: 4,
                    },
                    "o1",
                    "cap-1",
                )
                .await?;
            Ok(Value::Null)
        }
    };
    let (frame, outcome) = round_trip(&mut app, call).await;
    assert_eq!(frame["op"], "open_workspace_window");
    assert_eq!(frame["args"]["hostOrigin"], "http://127.0.0.1:51000");
    assert_eq!(frame["args"]["owner"], "o1");
    assert_eq!(frame["args"]["capability"], "cap-1");
    assert_eq!(
        frame["args"]["target"],
        json!({
            "workspaceId": "w1",
            "sessionId": "s1",
            "instanceId": "i1",
            "ownerId": "o1",
            "workspaceGeneration": 4,
        })
    );
    outcome.expect("the op completes");

    // save_session_export keeps initial_dir (row A5's live argument).
    let call = {
        let surface = Arc::clone(&surface);
        async move {
            surface
                .save_session_export(
                    "http://127.0.0.1:51000",
                    "/v2/session-export/0123456789abcdef0123456789abcdef",
                    "session.md",
                    Some("/tmp/exports".to_string()),
                )
                .await
        }
    };
    let (frame, outcome) = round_trip(&mut app, call).await;
    assert_eq!(frame["op"], "save_session_export");
    assert_eq!(
        frame["args"]["exportUrl"],
        "/v2/session-export/0123456789abcdef0123456789abcdef"
    );
    assert_eq!(frame["args"]["fileName"], "session.md");
    assert_eq!(frame["args"]["initialDir"], "/tmp/exports");
    outcome.expect("the op completes");

    // pane: the seven child-webview ops (row A13) travel as one tagged value.
    let call = {
        let surface = Arc::clone(&surface);
        async move {
            surface
                .pane(PaneOp::SetRect {
                    pane_id: "pane-1".to_string(),
                    rect: PaneRect {
                        x: 1.0,
                        y: 2.0,
                        width: 3.0,
                        height: 4.0,
                    },
                })
                .await
        }
    };
    let (frame, outcome) = round_trip(&mut app, call).await;
    assert_eq!(frame["op"], "pane");
    assert_eq!(
        frame["args"]["op"],
        json!({"kind": "set_rect", "paneId": "pane-1", "rect": {"x": 1.0, "y": 2.0, "width": 3.0, "height": 4.0}})
    );
    outcome.expect("the op completes");

    // pick_image_files / pick_folder keep their optional arguments.
    let call = {
        let surface = Arc::clone(&surface);
        async move {
            surface
                .pick_image_files(Some("/tmp/images".to_string()))
                .await
        }
    };
    let (frame, outcome) = round_trip(&mut app, call).await;
    assert_eq!(frame["op"], "pick_image_files");
    assert_eq!(frame["args"], json!({"initialDir": "/tmp/images"}));
    outcome.expect("the op completes");

    fixture.state.shutdown_graceful("test").await;
}
