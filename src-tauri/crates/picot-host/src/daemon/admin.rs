    /// Engineering-lesson #1: the fixtures below are typed **by hand from the
    /// protocol tables in the plan** (Task 3 "Interfaces — protocol"), never
    /// generated by round-tripping these Rust types. If a table changes, this
    /// test and the table change in the same commit; a type change alone breaks
    /// it.
    #[test]
    fn inbound_frames_match_the_protocol_tables_verbatim() {
        let hello = r#"{"type":"admin_hello","adminToken":"tok","role":"manager","appVersion":"0.5.0","buildId":"abc","pid":123}"#;
        match serde_json::from_str::<AdminInbound>(hello).expect("admin_hello parses") {
            AdminInbound::AdminHello {
                admin_token,
                role,
                app_version,
                build_id,
                pid,
            } => {
                assert_eq!(admin_token, "tok");
                assert_eq!(role, "manager");
                assert_eq!(app_version.as_deref(), Some("0.5.0"));
                assert_eq!(build_id.as_deref(), Some("abc"));
                assert_eq!(pid, Some(123));
            }
            other => panic!("wrong frame for admin_hello: {other:?}"),
        }

        let request = r#"{"type":"admin_request","id":"r1","op":"daemon.status","args":{}}"#;
        match serde_json::from_str::<AdminInbound>(request).expect("admin_request parses") {
            AdminInbound::AdminRequest { id, op, args } => {
                assert_eq!(id, "r1");
                assert_eq!(op, "daemon.status");
                assert_eq!(args, json!({}));
            }
            other => panic!("wrong frame for admin_request: {other:?}"),
        }

        let response = r#"{"type":"surface_response","id":"s1","ok":true,"result":{}}"#;
        match serde_json::from_str::<AdminInbound>(response).expect("surface_response parses") {
            AdminInbound::SurfaceResponse { id, ok, result } => {
                assert_eq!(id, "s1");
                assert!(ok);
                assert_eq!(result, json!({}));
            }
            other => panic!("wrong frame for surface_response: {other:?}"),
        }

        let progress = r#"{"type":"surface_progress","ackId":"s1","event":{}}"#;
        match serde_json::from_str::<AdminInbound>(progress).expect("surface_progress parses") {
            AdminInbound::SurfaceProgress { ack_id, event } => {
                assert_eq!(ack_id, "s1");
                assert_eq!(event, json!({}));
            }
            other => panic!("wrong frame for surface_progress: {other:?}"),
        }

        let ack = r#"{"type":"mirror_ack","permitId":"p1","epoch":3}"#;
        match serde_json::from_str::<AdminInbound>(ack).expect("mirror_ack parses") {
            AdminInbound::MirrorAck { permit_id, epoch } => {
                assert_eq!(permit_id, "p1");
                assert_eq!(epoch, 3);
            }
            other => panic!("wrong frame for mirror_ack: {other:?}"),
        }
    }

    /// The `daemon.status` reply's `agents` rows (T10 amendment): one row per
    /// live runtime, carrying the identity a restart stops plus the workspace
    /// root when the registry still knows it. A runtime in a workspace that left
    /// the registry is still **running** and therefore still listed — dropping
    /// it would make a restart's confirm dialog understate what it stops.
    #[test]
    fn a_status_agent_row_names_the_running_runtime_and_its_workspace() {
        let target =
            crate::runtime_coordinator::RuntimeTarget::with_owner("w1", "s1", "i1", "o1", 7);
        let row = agent_row(
            &target,
            Some(std::path::Path::new("/ws/proj")),
            Some(RuntimeState::Working),
        );
        assert_eq!(row["workspaceId"], "w1");
        assert_eq!(row["sessionId"], "s1");
        assert_eq!(row["instanceId"], "i1");
        assert_eq!(row["cwd"], "/ws/proj");
        assert_eq!(
            row["state"], "working",
            "the row carries the coordinator's own state, snake_case on the wire"
        );
        assert_eq!(
            row["streaming"], true,
            "`streaming` stays the mid-turn signal it always was"
        );

        let unregistered = agent_row(&target, None, Some(RuntimeState::Idle));
        assert_eq!(unregistered["workspaceId"], "w1");
        assert_eq!(
            unregistered["cwd"],
            Value::Null,
            "an unknown workspace root is null, not a fabricated path: {unregistered}"
        );
        assert_eq!(unregistered["streaming"], false);
        assert_eq!(unregistered["state"], "idle");

        // Every state the coordinator can hold is reported verbatim; a runtime
        // it no longer knows reports **null** rather than a fabricated state
        // (the settings list renders the row either way).
        for (state, wire) in [
            (RuntimeState::Starting, "starting"),
            (RuntimeState::Trusting, "trusting"),
            (RuntimeState::Ready, "ready"),
            (RuntimeState::Working, "working"),
            (RuntimeState::Idle, "idle"),
            (RuntimeState::Suspended, "suspended"),
            (RuntimeState::Crashed, "crashed"),
            (RuntimeState::Stopped, "stopped"),
        ] {
            let state_row = agent_row(&target, None, Some(state));
            assert_eq!(state_row["state"], wire);
            assert_eq!(
                state_row["streaming"],
                wire == "working",
                "`streaming` mirrors exactly the working state"
            );
        }
        assert_eq!(agent_row(&target, None, None)["state"], Value::Null);
        // The row never carries an owner or capability: it is a settings-panel
        // payload, not authorization state.
        let encoded = row.to_string();
        assert!(!encoded.contains("o1"), "{encoded}");
    }

