// ABOUTME: Task 5 protocol tests for the daemon-side app-surface forwarding: a real loopback
// ABOUTME: AdminServer, a real client socket playing the app, and the literal frame table.

//! Plan Task 5: the daemon has no windows, no dialogs and no updater, so every
//! forwarded row of the Task 2 inventory travels over the admin channel as an
//! `app_surface_request` frame and comes back as a `surface_response` (+
//! `surface_progress` while a streaming op runs).
//!
//! Both endpoints here are real: the daemon side is [`AdminForwardingSurface`]
//! over a production [`AdminServer`] on a loopback socket, and the app side is a
//! real `tokio-tungstenite` client speaking the **literal** frames of the
//! protocol table (engineering-lesson #1: the fixtures below are typed by hand
//! from the plan's table, never generated by round-tripping the Rust types).

use std::sync::{Arc, Mutex};
use std::time::Duration;

use futures_util::{SinkExt, StreamExt};
use picot_host::daemon::admin::{AdminConfig, AdminServer, ADMIN_WS_PATH};
use picot_host::daemon::app_surface::{AppSurface, PaneOp, SurfaceProgress};
use picot_host::daemon::surface_forward::wire;
use picot_host::daemon::surface_forward::AdminForwardingSurface;
use picot_host::daemon::{DaemonConfig, DaemonState};
use picot_host::host_server::PaneRect;
use picot_host::runtime_coordinator::RuntimeTarget;
use serde_json::{json, Value};
use tokio_tungstenite::tungstenite::Message;

type Client =
    tokio_tungstenite::WebSocketStream<tokio_tungstenite::MaybeTlsStream<tokio::net::TcpStream>>;

/// The forwarding deadline the tests inject: the production constant is 5s,
/// and waiting that out per assertion would make the suite slow, not stronger.
const SURFACE_DEADLINE: Duration = Duration::from_millis(300);

struct Fixture {
    _temp: tempfile::TempDir,
    state: Arc<DaemonState>,
    admin: AdminServer,
    surface: Arc<AdminForwardingSurface>,
    token: String,
}

impl Fixture {
    async fn boot() -> Self {
        let temp = tempfile::tempdir().expect("tempdir");
        let static_dir = temp.path().join("static");
        std::fs::create_dir_all(&static_dir).expect("static dir");
        std::fs::write(static_dir.join("index.html"), "<h1>surface</h1>").expect("index");
        let surface = Arc::new(AdminForwardingSurface::new());
        let state = Arc::new(
            DaemonState::start(
                DaemonConfig {
                    data_dir: temp.path().join("data"),
                    config_dir: temp.path().join("config"),
                    static_dir,
                    bundle_identifier: "com.palandata.picot.test".to_string(),
                },
                surface.clone(),
            )
            .await
            .expect("the daemon host stack boots"),
        );
        let token = "test-admin-token-0123456789abcdef".to_string();
        let admin = AdminServer::start(
            AdminConfig::new(token.clone())
                .with_mirror_ack_timeout(Duration::from_millis(300))
                .with_surface_forward_timeout(SURFACE_DEADLINE),
        )
        .await
        .expect("the admin listener binds");
        state.install_admin(admin.clone());
        surface.attach(admin.clone());
        Self {
            _temp: temp,
            state,
            admin,
            surface,
            token,
        }
    }

    fn ws_url(&self) -> String {
        format!(
            "ws://{}{ADMIN_WS_PATH}",
            self.admin.origin().trim_start_matches("http://")
        )
    }

    /// Connect a real client and complete the manager handshake.
    async fn attach_app(&self) -> Client {
        let (mut socket, _) = tokio_tungstenite::connect_async(self.ws_url())
            .await
            .expect("a real app socket connects");
        socket
            .send(Message::Text(
                json!({
                    "type": "admin_hello",
                    "adminToken": self.token,
                    "role": "manager",
                    "appVersion": "0.5.0",
                    "buildId": "test-build",
                    "pid": 4242,
                })
                .to_string(),
            ))
            .await
            .expect("hello sent");
        let welcome = next_json(&mut socket).await;
        assert_eq!(welcome["type"], "admin_welcome");
        socket
    }
}

async fn next_json(socket: &mut Client) -> Value {
    loop {
        let message = tokio::time::timeout(Duration::from_secs(15), socket.next())
            .await
            .expect("a frame within the deadline")
            .expect("the socket is open")
            .expect("a valid frame");
        match message {
            Message::Text(text) => return serde_json::from_str(&text).expect("a JSON frame"),
            Message::Close(frame) => panic!("the app socket closed: {frame:?}"),
            _ => continue,
        }
    }
}

async fn send_json(socket: &mut Client, frame: Value) {
    socket
        .send(Message::Text(frame.to_string()))
        .await
        .expect("frame sent");
}

fn keys(value: &Value) -> Vec<String> {
    let mut keys: Vec<String> = value
        .as_object()
        .expect("an object")
        .keys()
        .cloned()
        .collect();
    keys.sort();
    keys
}

/// Engineering-lesson #1: the op names are copied by hand from the plan's
/// `app_surface_request` table. A renamed op — or a 13th one — fails here.
#[test]
fn surface_op_names_match_the_protocol_table() {
    assert_eq!(
        wire::SURFACE_OPS.to_vec(),
        vec![
            "open_workspace_window",
            "open_devtools",
            "close_window",
            "cancel_window_close",
            "menu_state_changed",
            "relaunch_app",
            "pane",
            "pick_folder",
            "pick_image_files",
            "save_session_export",
            "check_for_update",
            "download_and_install_update",
        ]
    );
}

#[tokio::test(flavor = "multi_thread")]
async fn forwarded_op_travels_as_the_literal_frame_and_returns_its_result() {
    let fixture = Fixture::boot().await;
    let mut app = fixture.attach_app().await;

    let surface = Arc::clone(&fixture.surface);
    let call = tokio::spawn(async move { surface.pick_folder().await });

    let frame = next_json(&mut app).await;
    assert_eq!(
        keys(&frame),
        vec!["args", "id", "op", "type"],
        "the frame must match the protocol table exactly: {frame}"
    );
    assert_eq!(frame["type"], "app_surface_request");
    assert_eq!(frame["op"], "pick_folder");
    assert_eq!(frame["args"], json!({}));
    let id = frame["id"].as_str().expect("a string id").to_string();
    assert!(id.starts_with('s'), "surface ids are s-prefixed: {id}");

    send_json(
        &mut app,
        json!({"type": "surface_response", "id": id, "ok": true, "result": "/tmp/picked"}),
    )
    .await;

    let picked = tokio::time::timeout(Duration::from_secs(10), call)
        .await
        .expect("the forwarded op settles")
        .expect("no panic")
        .expect("the app's answer completes the op");
    assert_eq!(picked.as_deref(), Some("/tmp/picked"));
    fixture.state.shutdown_graceful("test").await;
}

#[tokio::test(flavor = "multi_thread")]
async fn a_failed_surface_response_becomes_an_error_for_the_requester() {
    let fixture = Fixture::boot().await;
    let mut app = fixture.attach_app().await;

    let surface = Arc::clone(&fixture.surface);
    let call = tokio::spawn(async move { surface.check_for_update().await });
    let frame = next_json(&mut app).await;
    assert_eq!(frame["type"], "app_surface_request");
    assert_eq!(frame["op"], "check_for_update");
    let id = frame["id"].as_str().unwrap().to_string();
    send_json(
        &mut app,
        json!({
            "type": "surface_response",
            "id": id,
            "ok": false,
            "result": {"error": "the updater is not configured"},
        }),
    )
    .await;

    let failure = tokio::time::timeout(Duration::from_secs(10), call)
        .await
        .expect("the forwarded op settles")
        .expect("no panic")
        .expect_err("ok=false must fail the requester");
    assert!(
        failure.contains("the updater is not configured"),
        "the app's message must reach the requester: {failure}"
    );
    fixture.state.shutdown_graceful("test").await;
}

#[tokio::test(flavor = "multi_thread")]
async fn surface_progress_frames_reach_the_requester_and_reset_the_idle_deadline() {
    let fixture = Fixture::boot().await;
    let mut app = fixture.attach_app().await;

    let events = Arc::new(Mutex::new(Vec::<Value>::new()));
    let sink: SurfaceProgress = {
        let events = Arc::clone(&events);
        Arc::new(move |event: Value| events.lock().unwrap().push(event))
    };
    let surface = Arc::clone(&fixture.surface);
    let call =
        tokio::spawn(async move { surface.download_and_install_update(sink).await.map(|_| ()) });

    let frame = next_json(&mut app).await;
    assert_eq!(frame["op"], "download_and_install_update");
    let id = frame["id"].as_str().unwrap().to_string();
    // Three progress frames, each one arriving inside the idle deadline: the
    // streaming op must outlive a total deadline (plan D5's 5s is an *idle*
    // deadline — see `AdminServer::request_app_surface`).
    for step in 1..=3 {
        tokio::time::sleep(SURFACE_DEADLINE / 2).await;
        send_json(
            &mut app,
            json!({
                "type": "surface_progress",
                "ackId": id,
                "event": {"phase": "download", "percent": step},
            }),
        )
        .await;
    }
    send_json(
        &mut app,
        json!({
            "type": "surface_response",
            "id": id,
            "ok": true,
            "result": {"installed": true},
        }),
    )
    .await;

    tokio::time::timeout(Duration::from_secs(10), call)
        .await
        .expect("the streaming op settles")
        .expect("no panic")
        .expect("progress frames keep the op alive");
    assert_eq!(
        *events.lock().unwrap(),
        vec![
            json!({"phase": "download", "percent": 1}),
            json!({"phase": "download", "percent": 2}),
            json!({"phase": "download", "percent": 3}),
        ],
        "every progress frame must reach the requester, in order"
    );
    fixture.state.shutdown_graceful("test").await;
}

#[tokio::test(flavor = "multi_thread")]
async fn a_silent_app_fails_the_op_with_the_typed_unavailable_error() {
    let fixture = Fixture::boot().await;
    let mut app = fixture.attach_app().await;

    let surface = Arc::clone(&fixture.surface);
    let call = tokio::spawn(async move { surface.menu_state_changed().await });
    let frame = next_json(&mut app).await;
    assert_eq!(frame["op"], "menu_state_changed");
    // Deliberately no response: the idle deadline must fire.
    let failure = tokio::time::timeout(Duration::from_secs(10), call)
        .await
        .expect("the op settles on its deadline")
        .expect("no panic")
        .expect_err("a silent app cannot serve the op");
    assert!(
        failure.starts_with("app_surface_unavailable:"),
        "the failure must be the typed one the client surfaces: {failure}"
    );
    assert!(
        failure.contains("300ms") || failure.contains("deadline"),
        "the failure must name the deadline: {failure}"
    );
    fixture.state.shutdown_graceful("test").await;
}

