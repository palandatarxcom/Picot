// ABOUTME: Extracts native host routes, commands, and production callers into a deterministic runtime inventory.
// ABOUTME: Generates both a reviewable Markdown matrix and machine-readable JSON without importing production modules.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const hostSource = await readFile(
  resolve(root, "src-tauri/crates/picot-host/src/host_server.rs"),
  "utf8",
);
const commandManifestPath = resolve(root, "protocol/picot-core-commands.json");
let commandManifest;
try {
  commandManifest = JSON.parse(await readFile(commandManifestPath, "utf8"));
} catch (error) {
  throw new Error(`Cannot read native command manifest ${commandManifestPath}: ${error}`);
}

function unique(values) {
  return [...new Set(values)].sort();
}

const hostRoutes = unique(
  [...hostSource.matchAll(/\.route\(\s*["']([^"']+)["']/g)].map((m) => m[1]),
);
const commands = Object.keys(commandManifest.commands).sort();

const files = [];
for (const directory of ["public", "extensions", "tests"]) {
  const glob = new Bun.Glob(`${directory}/**/*.{js,ts,html,mjs}`);
  for await (const file of glob.scan({ cwd: root, onlyFiles: true })) {
    if (file.startsWith("extensions/dist/")) continue;
    files.push(file);
  }
}
const callers = [];
for (const file of files.sort()) {
  const source = await readFile(resolve(root, file), "utf8");
  for (const [lineNumber, line] of source.split("\n").entries()) {
    if (/\bfetch\s*\(|\bsendControl\s*\(|\bpostRpc\s*\(|\bbroker_control\b/.test(line)) {
      callers.push({
        id: `${file}:${lineNumber + 1}`,
        file,
        line: lineNumber + 1,
        text: line.trim(),
      });
    }
  }
}

const hostControlSource = await readFile(resolve(root, "src-tauri/src/main.rs"), "utf8");
const routerSource = await readFile(
  resolve(root, "src-tauri/crates/picot-host/src/host_router.rs"),
  "utf8",
);
const controls = unique(
  [...hostControlSource.matchAll(/^\s*"([A-Za-z][A-Za-z0-9_.-]*)"\s*=>/gm)].map((m) => m[1]),
);
const hostFrames = unique(
  [
    ...routerSource.matchAll(
      /["'](runtime_[a-z_]+|host_[a-z_]+|hello(?:_ack)?|error|response|event|snapshot)["']/g,
    ),
  ].map((m) => m[1]),
);

const inventory = {
  version: 1,
  generatedBy: "scripts/migration-inventory.mjs",
  surfaces: {
    hostHttp: hostRoutes,
    nativeCommands: commands,
    // Retired Pi-origin `/ws` and `/api/rpc` are verified rejection contracts,
    // not active native surfaces; keep them out of the generated live inventory.
    websocket: ["/v2/ws", "browser connection", "extension_ui_response", "OAuth commands"],
    brokerControls: controls,
    hostFrames,
  },
  callers,
  counts: {
    hostHttp: hostRoutes.length,
    nativeCommands: commands.length,
    callers: callers.length,
    brokerControls: controls.length,
    hostFrames: hostFrames.length,
  },
};

const outputPath =
  process.env.MIGRATION_INVENTORY_OUTPUT ?? resolve(root, "scripts/gen/inventory.json");
// Generated report goes to gen/ only — the curated Gate A document under
// docs/ is human-maintained and must never be overwritten by the generator.
const docPath =
  process.env.MIGRATION_INVENTORY_DOC ?? resolve(root, "scripts/gen/inventory-report.md");
await mkdir(resolve(root, "scripts/gen"), { recursive: true });
await mkdir(resolve(root, "docs/superpowers/specs"), { recursive: true });
const inventoryJson = JSON.stringify(inventory, null, 2).replace(
  '    "websocket": [\n      "/v2/ws",\n      "browser connection",\n      "extension_ui_response",\n      "OAuth commands"\n    ],',
  '    "websocket": ["/v2/ws", "browser connection", "extension_ui_response", "OAuth commands"],',
);
await writeFile(outputPath, `${inventoryJson}\n`);
const lines = [
  "# Native Runtime Migration Inventory",
  "",
  "> Generated by `bun run migration:inventory`. Review callers and assign Gate A IDs before migration work.",
  "",
  `Generated counts: HTTP ${hostRoutes.length}, commands ${commands.length}, callers ${callers.length}, broker controls ${controls.length}, host frames ${hostFrames.length}.`,
  "",
  "## Host HTTP routes",
  "",
  ...hostRoutes.map((path, index) => {
    const retired = path === "/api/rpc" || path === "/ws";
    const status = retired ? " *(retired: explicit rejection)*" : "";
    return `- HOST-HTTP-${String(index + 1).padStart(2, "0")} \`${path}\`${status}`;
  }),
  "",
  "## Native commands",
  "",
  ...commands.map(
    (command, index) => `- NATIVE-CMD-${String(index + 1).padStart(2, "0")} \`${command}\``,
  ),
  "",
  "## Broker controls and host frames",
  "",
  `- Broker controls: ${controls.map((value) => `\`${value}\``).join(", ") || "(none extracted; review dispatch_control manually)"}`,
  `- Host frames: ${hostFrames.map((value) => `\`${value}\``).join(", ") || "(none extracted; review host_router manually)"}`,
  "",
  "## Production callers",
  "",
  ...callers.map(
    (caller, index) =>
      `- A-CALLER-${String(index + 1).padStart(3, "0")} \`${caller.file}:${caller.line}\` — ${caller.text}`,
  ),
  "",
  "## Review notes",
  "",
  "- Extraction is syntax-oriented and reports current host/native surfaces; it does not grant authority to browser payloads.",
  "- A-CALLER-NNN are sorted positions and drift on insertion; stable references use the caller `id` (`file:line`) field.",
  "- Route and command counts are generated from HostServer and the canonical command manifest, not hard-coded.",
  "- Review `dispatch_control`, OAuth, extension UI, static assets, and binary/download paths against source before release.",
];
await writeFile(docPath, `${lines.join("\n")}\n`);
console.log(`Wrote ${relative(root, outputPath)} and ${relative(root, docPath)}`);
