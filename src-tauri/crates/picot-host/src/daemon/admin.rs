// ABOUTME: The daemon's admin channel: loopback WS with a single manager lease, attachment epochs,
// ABOUTME: and the navigation mirror (plan Task 3 protocol tables — fixtures in tests pin them literally).

//! # Admin channel (plan D3, B6/R1 server side)
//!
//! One bidirectional loopback WebSocket, `GET /admin`, authenticated by the
//! daemon's high-entropy `adminToken`. A `admin_hello{role:"manager"}` acquires
//! the single manager lease atomically and increments the **attachment epoch**;
//! a competing *live* manager is closed `4409` without disturbing the incumbent.
//! Probing never comes here (read-only instance file + `/health`, T4).
//!
//! Frame shapes are the task's protocol tables. `tests/`-level fixtures pin the
//! *literal* JSON of those tables (engineering-lesson #1): the fixtures are
//! written from the tables, never generated by round-tripping these types.
//!
//! ## Timing rules (R1)
//!
//! - Every connection has its own reader loop, and each `admin_request` is
//!   dispatched on its own task, so a slow op never stalls a later one; the
//!   writer side is a single outbound queue per connection.
//! - Responses carry their request `id`; nothing is matched by arrival order.
//! - Registry/mutex locks are taken only to clone data and are never held
//!   across an await.
//!
//! ## Drain order (plan Task 3 risks)
//!
//! `daemon.stop` replies *accepted*, then: stop accepting admin frames → close
//! the admin WS → drain runtimes → files → exit. The observer steps live in
//! [`crate::daemon::DrainStep`] and the file step is T4's plug point.

