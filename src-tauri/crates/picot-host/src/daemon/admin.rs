/// The admin WS path (plan D3: a second listener, never LAN-gated).
pub const ADMIN_WS_PATH: &str = "/admin";

/// Close code: the `adminToken` did not match.
pub const ADMIN_CLOSE_BAD_TOKEN: u16 = 4401;
/// Close code: another live manager already holds the lease.
pub const ADMIN_CLOSE_LEASE_HELD: u16 = 4409;
/// Close code: a malformed frame (pre-hello, or a connection-level protocol
/// violation afterwards).
pub const ADMIN_CLOSE_MALFORMED: u16 = 4410;

/// Bounded wait for the app's `mirror_ack` after a `navigation_permit` push.
/// Plan Task 3: "`mirror_ack` timeout choice (5s) recorded as a constant". On
/// timeout the granting op fails **safe**: the permit is revoked, so the
/// WebView's synchronous delegate can never hit a permit the app never
/// installed.
pub const MIRROR_ACK_TIMEOUT: Duration = Duration::from_secs(5);

/// Bounded wait for the app's `surface_response` after an `app_surface_request`
/// push (plan D5: "forwarding timeout 5s → typed `app_surface_unavailable`").
///
/// Implementation-time decision: this is an **idle** deadline — every
/// `surface_progress` frame restarts it — because
/// `download_and_install_update` streams for minutes: a *total* 5s deadline
/// would make updates impossible in external mode, while the plan's intent (a
/// forwarding call must not hang, and silence means the app is gone) is exactly
/// what an idle deadline enforces. See [`AdminServer::request_app_surface`].
pub const SURFACE_FORWARD_TIMEOUT: Duration = Duration::from_secs(5);

// The `owner.close_request` settlement deadline is not a constant here: the
// production value lives with the bridge that needs it
// (`daemon::owner_close::CLOSE_REQUEST_SETTLE_TIMEOUT`), and the admin config
// only carries it so tests do not wait 30s for the deadline.

/// Grace window between "the manager's socket dropped" and "mark the
/// attachment dead" (plan D11). A reconnect inside the window keeps the
/// attachment; otherwise capabilities are revoked and labels freed.
pub const DEAD_ATTACHMENT_GRACE: Duration = Duration::from_secs(2);

/// The daemon's `version` reported by `daemon.status` / `admin_welcome`.
pub const DAEMON_VERSION: &str = env!("CARGO_PKG_VERSION");

/// `admin_hello` must carry this role; anything else is malformed.
const MANAGER_ROLE: &str = "manager";

/// Who holds the manager lease, as the daemon needs to publish it (plan D3:
/// adoption is a daemon-authorized transaction — the daemon rewrites the
/// instance file's manager record on grant and clears it when the attachment
/// dies).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ManagerIdentity {
    pub pid: Option<u32>,
    pub app_version: Option<String>,
    pub build_id: Option<String>,
}

/// Notified whenever the manager lease changes (grant, supersede, dead
/// attachment). Implemented by the daemon's instance-file owner
/// ([`crate::daemon::instance::InstanceStore`]).
///
/// Called **without** any admin lock held, so an implementation may do file
/// I/O; it must not block (it runs on the connection task).
pub trait LeaseObserver: Send + Sync {
    /// `Some` after a grant, `None` when the attachment died or was superseded.
    fn manager_changed(&self, manager: Option<ManagerIdentity>);
}

